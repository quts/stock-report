class Rows(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.rows, self.row, self.cell = [], [], None

    def handle_starttag(self, tag, attrs):
        if tag == 'tr':
            self.row = []
        elif tag in ('th', 'td'):
            self.cell = []
        elif self.cell is not None:
            self.cell.append(self.get_starttag_text())

    def handle_endtag(self, tag):
        if tag in ('th', 'td') and self.cell is not None:
            self.row.append(''.join(self.cell))
            self.cell = None
        elif tag == 'tr':
            self.rows.append(self.row)
        elif self.cell is not None:
            self.cell.append(f'</{tag}>')

    def handle_data(self, data):
        if self.cell is not None:
            self.cell.append(data)

    def handle_entityref(self, name):
        self.handle_data(f'&{name};')

    def handle_charref(self, name):
        self.handle_data(f'&#{name};')


def cards(table):
    parser = Rows()
    parser.feed(table)
    if not parser.rows:
        return table
    headers, *rows = parser.rows
    out = [f'<div class="mobile-table-title">{headers[0]}</div>']
    for row in rows:
        if not row:
            continue
        out.append(f'<section class="mobile-record"><h4>{row[0]}</h4><dl>')
        for i, value in enumerate(row[1:], 1):
            label = headers[i] if i < len(headers) else ''
            out.append(f'<div class="mobile-field"><dt>{label}</dt><dd>{value}</dd></div>')
        out.append('</dl></section>')
    return ''.join(out)


def reflow(html):
    # Tables are generated by the trusted template; cell content is already escaped by Jinja.
    # Keep every cell, including citations and labels, rather than shortening financial content.
    import re
    html = re.sub(r'<table\b[^>]*>.*?</table>', lambda m: cards(m.group()), html, flags=re.S)
    return html.replace('</head>', STYLE + '</head>')
